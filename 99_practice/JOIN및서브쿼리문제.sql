-- 1. 70년대 생(1970~1979) 중 여자이면서 전씨인 사원의 이름과 주민번호, 부서 명, 직급 조회

SELECT EMP_NAME, EMP_NO, DEPT_TITLE, JOB_CODE
FROM EMPLOYEE
JOIN DEPARTMENT ON(DEPT_ID = DEPT_CODE)
WHERE EMP_NAME LIKE '전%' AND 
     (TO_NUMBER(SUBSTR(EMP_NO,1,2)) BETWEEN 70 AND 79);
     
-- 2. 나이 상 가장 막내의 사원 코드, 사원 명, 나이, 부서 명, 직급 명 조회


SELECT EMP_ID, EMP_NAME, AGE, DEPT_TITLE, JOB_NAME
FROM (SELECT EMP_ID, EMP_NAME, TRUNC(MONTHS_BETWEEN(SYSDATE,TO_DATE('19' || SUBSTR(EMP_NO, 1, 2), 'YYYY')) / 12) AS AGE, DEPT_TITLE, JOB_NAME
      FROM EMPLOYEE E
      JOIN DEPARTMENT D ON E.DEPT_CODE = D.DEPT_ID
      JOIN JOB J ON E.JOB_CODE = J.JOB_CODE
      ORDER BY AGE)
WHERE ROWNUM = 1;    
    
    

